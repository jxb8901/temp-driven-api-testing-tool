class JobStoreTest {
    @TempDir Path temp;

    private static java.sql.Connection schemaConnection(String url) throws Exception {
        java.util.Properties credentials=new java.util.Properties();credentials.setProperty("user","sa");credentials.setProperty("password","");
        return new org.h2.Driver().connect(url,credentials);
    }
    @Test void addsPinReasonAndAuditDetailIdempotentlyToAnExistingDatabase() throws Exception {
        Path allowed=Files.createDirectory(temp.resolve("migration-packages"));Path pkg=Files.createDirectory(allowed.resolve("p"));Path data=temp.resolve("migration-data");
        Path configFile=temp.resolve("migration-server.yaml");Files.writeString(configFile,"server:\n  dataDir: "+data+"\nworkers: {}\npackages:\n  allowedRoots:\n    - "+allowed+"\n  entries:\n    p: "+pkg+"\n");
        ServerConfig config=ServerConfig.load(configFile);Files.createDirectories(data.resolve("db"));

        String url="jdbc:h2:file:"+data.resolve("db/att-server").toString().replace('\\','/')+";DB_CLOSE_ON_EXIT=FALSE;AUTO_SERVER=FALSE";
        try(var connection=schemaConnection(url);var statement=connection.createStatement()) {
            statement.execute("CREATE TABLE jobs (job_id VARCHAR(80) PRIMARY KEY, command VARCHAR(16) NOT NULL, package_id VARCHAR(64) NOT NULL, principal VARCHAR(256) NOT NULL, status VARCHAR(24) NOT NULL, created_at VARCHAR(40) NOT NULL, started_at VARCHAR(40), finished_at VARCHAR(40), worker_pid BIGINT, exit_code INT, result_json CLOB, diagnostic_json CLOB, request_summary CLOB NOT NULL)");
            statement.execute("CREATE TABLE audit (audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, principal VARCHAR(256) NOT NULL, action VARCHAR(32) NOT NULL, job_id VARCHAR(80), package_id VARCHAR(64), created_at VARCHAR(40) NOT NULL, outcome VARCHAR(32) NOT NULL)");
        }
        new JobStore(config).close();new JobStore(config).close();
        try(var connection=schemaConnection(url);var statement=connection.createStatement()) {
            assertDoesNotThrow(()->statement.executeQuery("SELECT pin_reason FROM jobs").close());
            assertDoesNotThrow(()->statement.executeQuery("SELECT detail FROM audit").close());
        }
    }

    @Test void persistsJobIdentityLifecycleAndDeterministicRestartRecovery() throws Exception {
        Path allowed=Files.createDirectory(temp.resolve("packages"));Path pkg=Files.createDirectory(allowed.resolve("payments"));
        Path java=Path.of(System.getProperty("java.home"),"bin",System.getProperty("os.name","").toLowerCase().contains("win")?"java.exe":"java");
        Path configFile=temp.resolve("server.yaml");Files.writeString(configFile,"server:\n  dataDir: "+temp.resolve("data")+"\n  javaExecutable: "+java+"\nworkers: {}\npackages:\n  allowedRoots:\n    - "+allowed+"\n  entries:\n    payments: "+pkg+"\n");
        ServerConfig config=ServerConfig.load(configFile);JobStore store=new JobStore(config);
        Job job=new Job("J0123456789ABCDEF","run","payments","ci-build",new WorkerRequest(),new JobEvents(config.dataDir.resolve("jobs/J0123456789ABCDEF/events.jsonl"),100));
        store.insert(job,"{\"command\":\"run\",\"packageId\":\"payments\"}");store.audit("ci-build","SUBMIT",job.id,job.packageId,"ACCEPTED");
        assertEquals("QUEUED",store.get(job.id).get("status"));assertEquals(1,store.count("QUEUED"));
        job.status="RUNNING";job.workerPid=99999999L;job.workerStartTime=Instant.now();store.update(job);
        assertEquals(1,store.staleWorkers().size());store.interruptStale(job.id);
        Map<String,Object> restored=store.get(job.id);assertEquals("ERROR",restored.get("status"));assertTrue(((String)restored.get("diagnosticJson")).contains("ATT-SERVER-INTERRUPTED"));
        store.close();
    }

    @Test void persistsWorkerPerformanceMetadataAcrossStoreReads() throws Exception {
        Path allowed=Files.createDirectory(temp.resolve("performance-packages"));Path pkg=Files.createDirectory(allowed.resolve("package"));
        Path java=Path.of(System.getProperty("java.home"),"bin",System.getProperty("os.name","").toLowerCase().contains("win")?"java.exe":"java");
        Path configFile=temp.resolve("performance-server.yaml");Files.writeString(configFile,"server:\n  dataDir: "+temp.resolve("performance-data")+"\n  javaExecutable: "+java+"\nworkers: {}\npackages:\n  allowedRoots:\n    - "+allowed+"\n  entries:\n    p: "+pkg+"\n");
        ServerConfig config=ServerConfig.load(configFile);JobStore store=new JobStore(config);
        Job job=new Job("J1111111111111111","run","p","test",new WorkerRequest(),new JobEvents(config.dataDir.resolve("jobs/J1111111111111111/events.jsonl"),100));
        job.requestReceivedNanos=1_000_000L;job.admittedNanos=2_500_000L;job.workerStartedNanos=4_000_000L;
        job.workerSpawnStartedNanos=4_500_000L;job.workerSpawnedNanos=6_000_000L;job.workerReadyNanos=8_000_000L;
        job.executionReadyNanos=11_000_000L;job.resultReceivedNanos=20_000_000L;job.workerTerminatedNanos=22_000_000L;
        job.workerMetrics=Map.of("heapPeakUsedBytes",4096L,"processCpuSupported",true);
        store.insert(job,"{}");store.update(job);

        Map<String,Object> restored=store.get(job.id);
        Map<String,Object> performance=ServerRuntime.JSON.readValue((String)restored.get("performanceJson"),Map.class);
        Map<?,?> timings=(Map<?,?>)performance.get("timings");
        assertEquals(1.5,((Number)timings.get("admissionMs")).doubleValue());
        assertEquals(1.5,((Number)timings.get("queueWaitMs")).doubleValue());
        assertEquals(2.0,((Number)timings.get("workerReadyMs")).doubleValue());
        assertEquals(2.0,((Number)timings.get("resultToTerminationMs")).doubleValue());
        assertEquals(4096L,((Number)((Map<?,?>)performance.get("worker")).get("heapPeakUsedBytes")).longValue());
        store.close();
    }

    @Test void replayIntentsAndOwnershipSurviveRestartAndOutputDeletion() throws Exception {
        Path pkg=Files.createDirectory(temp.resolve("replay-package"));Path configFile=temp.resolve("replay-server.yaml");
        Files.writeString(configFile,"server:\n  dataDir: "+temp.resolve("replay-data")+"\nworkers: {}\npackages:\n  allowedRoots: ["+pkg+"]\n  entries:\n    p: "+pkg+"\n");
        ServerConfig config=ServerConfig.load(configFile);
        Job job=new Job("J1111111111111111","run","p","alice",new WorkerRequest(),new JobEvents(temp.resolve("replay-events.jsonl"),100));
        job.replayOwner="alice";job.rerunOfJobId="J0000000000000000";job.replayIntent="intent";
        var definition=ServerRuntime.JSON.createObjectNode();definition.put("schemaVersion",RunDefinition.VERSION);definition.put("executionType","run");definition.put("packageId","p");definition.putObject("selection").putArray("caseIds").add("suite.C1");
        job.executionSpec=new JobExecutionSpec(definition,"a".repeat(64),null).json();
        try(JobStore store=new JobStore(config)){store.insert(job,"{}");}
        try(JobStore restored=new JobStore(config)) {
            assertEquals(job.executionSpec,restored.executionSpec(job.id).get("spec"));
            assertEquals("alice",restored.executionSpec(job.id).get("principal"));
            assertNull(restored.replayJob("bob","intent",job.rerunOfJobId));
            assertEquals(job.id,restored.replayJob("alice","intent",job.rerunOfJobId));
            restored.deleteJob(job.id);
            assertEquals(job.id,restored.replayJob("alice","intent",job.rerunOfJobId),"Deletion must not turn a retry into a new execution");
            Job duplicate=new Job("J2222222222222222","run","p","alice",new WorkerRequest(),new JobEvents(temp.resolve("duplicate.jsonl"),100));
            duplicate.replayIntent=job.replayIntent;duplicate.rerunOfJobId=job.rerunOfJobId;
            assertThrows(Exception.class,()->restored.insert(duplicate,"{}"));
            assertNull(restored.get(duplicate.id),"Rejected intent must roll back Job insertion too");
        }
    }
}
